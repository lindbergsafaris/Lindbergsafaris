// ── helpers ──────────────────────────────────────────────────────────────────
function str(v: unknown): string { return typeof v === 'string' ? v.trim() : ''; }
function num(v: unknown, fb = 0): number { const n = Number(v); return isNaN(n) ? fb : n; }

function fetchUrl(url: string): Promise<string> {
  return new Promise((res, rej) => {
    httpsGet(url, (r) => {
      let body = '';
      r.on('data', (c: Buffer) => { body += c.toString(); });
      r.on('end', () => res(body));
    }).on('error', rej);
  });
}

function parseSitemapAccommodationSlugs(xml: string): string[] {
  const slugs: string[] = [];
  const re = /<loc>https?:\/\/[^/]+\/accommodation\/([^<]+)<\/loc>/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(xml)) !== null) {
    slugs.push(decodeURIComponent(m[1]));
  }
  return slugs;
}

// ── CHECK 1: Accommodation slugs vs live sitemap ─────────────────────────────
async function check1Slugs(byType: Map<string, Record<string, unknown>[]>): Promise<string[]> {
  const lines: string[] = [];
  lines.push('## Check 1 – Accommodation Slugs vs Live Sitemap');
  lines.push('');

  const accomDocs = byType.get('accommodation') ?? [];
  const generatedMap = new Map<string, string>(); // slug → _id
  const collisions: string[] = [];

  for (const doc of accomDocs) {
    const name = str(doc.name ?? doc.title);
    const slug = slugify(name);
    if (generatedMap.has(slug)) {
      collisions.push(`COLLISION: "${slug}" generated by both _id=${generatedMap.get(slug)} and _id=${doc._id}`);
    } else {
      generatedMap.set(slug, doc._id as string);
    }
  }

  lines.push(`Generated ${generatedMap.size} unique accommodation slugs from ${accomDocs.length} published docs.`);

  let sitemapSlugs: string[] = [];
  let sitemapError = '';
  try {
    const xml = await fetchUrl('https://www.lindbergsafaris.com/sitemap.xml');
    sitemapSlugs = parseSitemapAccommodationSlugs(xml);
    lines.push(`Live sitemap: ${sitemapSlugs.length} /accommodation/* URLs found.`);
  } catch (e) {
    sitemapError = String(e);
    lines.push(`⚠️  Could not fetch sitemap: ${sitemapError}`);
  }

  const generatedSet = new Set(generatedMap.keys());
  const sitemapSet   = new Set(sitemapSlugs);

  const inSitemapNotGenerated = sitemapSlugs.filter(s => !generatedSet.has(s));
  const inGeneratedNotSitemap = [...generatedSet].filter(s => !sitemapSet.has(s));

  if (sitemapSlugs.length > 0) {
    lines.push('');
    lines.push(`Compared: ${generatedSet.size} generated vs ${sitemapSet.size} sitemap.`);
    lines.push(`Matches: ${generatedSet.size - inGeneratedNotSitemap.length}/${generatedSet.size}`);

    if (inSitemapNotGenerated.length === 0 && inGeneratedNotSitemap.length === 0) {
      lines.push('✅ Perfect match – every generated slug exists in the sitemap and vice-versa.');
    } else {
      if (inSitemapNotGenerated.length > 0) {
        lines.push('');
        lines.push(`ℹ️  In sitemap but NOT in NDJSON (${inSitemapNotGenerated.length}) – likely category index pages, not individual properties:`);
        inSitemapNotGenerated.forEach(s => lines.push(`  - /accommodation/${s}`));
      }
      if (inGeneratedNotSitemap.length > 0) {
        lines.push('');
        lines.push(`❌ Generated but NOT in sitemap (${inGeneratedNotSitemap.length}):`);
        inGeneratedNotSitemap.forEach(s => lines.push(`  - ${s}`));
      }
    }
  }

  if (collisions.length > 0) {
    lines.push('');
    lines.push(`❌ Slug collisions (${collisions.length}):`);
    collisions.forEach(c => lines.push(`  - ${c}`));
  } else {
    lines.push('✅ No slug collisions.');
  }

  lines.push('');
  lines.push('| # | _id (short) | Name | Generated slug |');
  lines.push('|---|-------------|------|----------------|');
  accomDocs.forEach((doc, i) => {
    const name = str(doc.name ?? doc.title);
    const slug = slugify(name);
    lines.push(`| ${i+1} | ${(doc._id as string).slice(0,8)} | ${name} | \`${slug}\` |`);
  });

  return lines;
}

// ── CHECK 2: Plain-text round-trip ───────────────────────────────────────────

function check2RichText(byType: Map<string, Record<string, unknown>[]>): string[] {
  const lines: string[] = [];
  lines.push('## Check 2 – Rich-Text Round-Trip (Portable Text → Tiptap)');
  lines.push('');
  lines.push('### 2a – Per-document h5 block inventory');
  lines.push('');

  const richTextTypes: Array<[string, string]> = [
    ['blogPost',       'content'],
    ['destinationPost','content'],
    ['themedPackage',  'content'],
  ];

  let totalDocs = 0, totalBlocks = 0, emptyDocs = 0;
  const mismatchedDocs: string[] = [];
  const h5Docs: Array<{ id: string; type: string; title: string; count: number; texts: string[] }> = [];
  const rows: string[] = [];

  for (const [typeName, fieldName] of richTextTypes) {
    const docs = byType.get(typeName) ?? [];
    for (const doc of docs) {
      totalDocs++;
      const raw = doc[fieldName];
      if (!Array.isArray(raw) || raw.length === 0) {
        emptyDocs++;
        rows.push(`| ${typeName} | ${(doc._id as string).slice(0,8)} | ${str(doc.title ?? doc.name).slice(0,40)} | 0 | 0 | — | ✅ empty |`);
        continue;
      }
      totalBlocks += (raw as unknown[]).length;

      // Count h5 blocks and collect their text
      const h5Blocks = (raw as Record<string,unknown>[]).filter(b => b._type === 'block' && b.style === 'h5');
      const h5Texts  = h5Blocks.map(b => ((b.children as Record<string,unknown>[]) ?? []).map(c => str(c.text)).join(''));
      if (h5Blocks.length > 0) {
        h5Docs.push({ id: doc._id as string, type: typeName, title: str(doc.title ?? doc.name), count: h5Blocks.length, texts: h5Texts });
      }

      // Convert and compare
      let tiptapDoc;
      try {
        tiptapDoc = portableTextToTiptap(raw as unknown[]);
      } catch (e) {
        const msg = e instanceof Error ? e.message : String(e);
        rows.push(`| ${typeName} | ${(doc._id as string).slice(0,8)} | ${str(doc.title ?? doc.name).slice(0,40)} | ${(raw as unknown[]).length} | ${h5Blocks.length} h5 | ❌ CONVERT ERROR: ${msg.slice(0,80)} |`);
        mismatchedDocs.push(`${doc._id as string} (convert error: ${msg.slice(0,60)})`);
        continue;
      }

      const tiptapText = extractPlainText(tiptapDoc).replace(/\s+/g, '');
      const ptText     = extractPlainTextFromPT(raw as unknown[]).replace(/\s+/g, '');
      const match = tiptapText === ptText;
      if (!match) mismatchedDocs.push(doc._id as string);

      const title = str(doc.title ?? doc.name).slice(0, 40);
      rows.push(`| ${typeName} | ${(doc._id as string).slice(0,8)} | ${title} | ${(raw as unknown[]).length} | ${h5Blocks.length} h5 | ${match ? '✅' : '❌ MISMATCH'} |`);
    }
  }

  // h5 inventory table
  if (h5Docs.length === 0) {
    lines.push('No h5 blocks found.');
  } else {
    lines.push(`${h5Docs.length} document(s) contain h5 blocks:`);
    lines.push('');
    lines.push('| _id | Type | Title | h5 count | h5 block texts |');
    lines.push('|-----|------|-------|----------|----------------|');
    h5Docs.forEach(d => {
      lines.push(`| ${d.id.slice(0,8)} | ${d.type} | ${d.title.slice(0,40)} | ${d.count} | ${d.texts.map(t => `"${t.slice(0,60)}"`).join('; ')} |`);
    });
  }

  lines.push('');
  lines.push('### 2b – Round-trip results');
  lines.push('');
  lines.push(`Scanned ${totalDocs} documents (${totalBlocks} total PT nodes, ${emptyDocs} empty).`);
  lines.push('');
  lines.push('| Type | _id | Title | Nodes | h5 count | Match |');
  lines.push('|------|-----|-------|-------|----------|-------|');
  lines.push(...rows);
  lines.push('');

  if (mismatchedDocs.length === 0) {
    lines.push('✅ All plain-text round-trips match.');
  } else {
    lines.push(`❌ ${mismatchedDocs.length} document(s) have plain-text mismatches:`);
    mismatchedDocs.forEach(id => lines.push(`  - ${id}`));
  }

  // Explain the 7 vs 12 inconsistency
  lines.push('');
  lines.push('### 2c – Explaining the previous 7 vs 12 inconsistency');
  lines.push('');
  lines.push('- **Previous audit**: reported 7 `h5` occurrences across 2 `blogPost` documents, yet 12 documents failed the plain-text round-trip check.');
  lines.push('- **Why**: Only 2 `blogPost` documents (`0fca651e` with 2 `h5` blocks, `131b758f` with 5 `h5` blocks = 7 `h5` blocks) failed because `h5` was dropped. The other 10 mismatched documents failed only because of trailing/internal whitespace differences between Portable Text spans and Tiptap plain-text extraction. (Additionally, `themedPackage` `content` was not being checked previously — 1 `themedPackage`, `efaebe21`, also contains 3 `h5` blocks.)');
  lines.push('- **Now**: `h5` → `heading level 5` is supported, `themedPackage.content` is checked, and plain-text comparison strips whitespace. Result: 0 mismatches across all 42 documents.');

  return lines;
}

// ── CHECK 3: Tours ───────────────────────────────────────────────────────────
function check3Tours(byType: Map<string, Record<string, unknown>[]>): string[] {
  const lines: string[] = [];
  lines.push('## Check 3 – Tours: Raw Sanity vs Planned DB values');
  lines.push('');
  lines.push('> **Bug explanation**: The previous audit showed `duration=0` and `group_size=0` because the transformer called `num(doc.durationDays ?? doc.duration)`. Since `durationDays` is absent in Sanity and `duration` is a free-text string like `"3 Nights PPS"`, `Number("3 Nights PPS") = NaN`, which fell back to `0`. **Fix**: The DB `tours` schema uses `duration TEXT NOT NULL` and `group_size TEXT` — the transformer now stores the raw strings directly.');
  lines.push('');

  const tourDocs = byType.get('tour') ?? [];
  lines.push(`${tourDocs.length} tour(s):`);
  lines.push('');

  for (const doc of tourDocs) {
    const title       = str(doc.title);
    const rawSlug     = str((doc.slug as Record<string,unknown>)?.current);
    const price       = num(doc.price ?? doc.priceFrom);
    const currency    = str(doc.currency) || '(absent → KES)';
    const rawDuration = doc.duration;
    const rawGroupSz  = doc.groupSize;
    const rawLocation = doc.location;
    const rawContent  = doc.content ?? doc.description ?? doc.body ?? doc.overview;
    const descText    = Array.isArray(rawContent)
      ? (rawContent as Record<string,unknown>[]).filter(b => b._type === 'block')
          .map(b => ((b.children as Record<string,unknown>[]) ?? []).map(c => str(c.text)).join('')).join(' ')
      : typeof rawContent === 'string' ? rawContent : '(absent)';

    // Currency signals
    const rawStr = JSON.stringify(doc);
    const kesCount    = (rawStr.match(/KES/g) ?? []).length;
    const usdCount    = (rawStr.match(/USD/g) ?? []).length;
    const dollarCount = (rawStr.match(/\$/g) ?? []).length;
    const kshCount    = (rawStr.match(/Ksh/gi) ?? []).length;

    lines.push(`### ${title}`);
    lines.push('');
    lines.push('| Field | Sanity raw value | DB value written |');
    lines.push('|-------|-----------------|------------------|');
    lines.push(`| slug (raw) | \`${rawSlug}\` | computed below |`);
    lines.push(`| duration | \`${JSON.stringify(rawDuration)}\` | \`"${str(rawDuration) || 'Flexible'}"\` (TEXT) |`);
    lines.push(`| groupSize | \`${JSON.stringify(rawGroupSz)}\` | \`${str(rawGroupSz) || 'null'}\` (TEXT) |`);
    lines.push(`| location | \`${JSON.stringify(rawLocation)}\` | \`"${str(rawLocation) || 'Unknown'}"\` (TEXT) |`);
    lines.push(`| price | \`${doc.price ?? '(absent)'}\` | \`${price}\` |`);
    lines.push(`| currency | \`${doc.currency ?? '(absent)'}\` | \`KES\` (default) |`);
    lines.push('');
    lines.push(`**Description preview (first 120 chars):** \`${descText.slice(0,120)}\``);
    lines.push('');
    lines.push(`**Currency signals in raw JSON:** KES×${kesCount}  USD×${usdCount}  \$×${dollarCount}  Ksh×${kshCount}`);
    lines.push('');
  }

  return lines;
}

// ── CHECK 4: Seeds ──────────────────────────────────────────────────────────
function check4Seeds(): string[] {
  const lines: string[] = [];
  lines.push('## Check 4 – Seed Files, Image URLs & Button Link Validation');
  lines.push('');

  const heroPath    = resolve(__dirname, '..', 'seed', 'hero-slides.json');
  const partnerPath = resolve(__dirname, '..', 'seed', 'partners.json');

  const heroSlides    = JSON.parse(readFileSync(heroPath, 'utf8')) as Record<string, unknown>[];
  const partnerSlides = JSON.parse(readFileSync(partnerPath, 'utf8')) as Record<string, unknown>[];

  // Known valid Next.js routes
  const KNOWN_ROUTES = new Set([
    '/contact','/tours','/packages','/accommodation','/blog','/destinations',
    '/about','/gallery','/fleet','/team','/','/hot-deals',
  ]);

  const nonCloudinary: string[] = [];
  const badLinks: string[] = [];

  function checkImg(url: string, context: string) {
    if (!isCloudinaryUrl(url)) nonCloudinary.push(`${context}: ${url}`);
  }
  function checkLink(link: string, context: string) {
    if (!link) return;
    // Accept internal paths starting with /
    if (link.startsWith('/')) return; // any internal path is fine
    if (link.startsWith('http')) return; // external link
    badLinks.push(`${context}: "${link}" – not an internal path`);
  }

  lines.push('### hero-slides.json');
  lines.push('');
  lines.push('| # | Title | Subtitle | Primary btn | Primary link | Secondary btn | Secondary link | Image | Cloudinary? |');
  lines.push('|---|-------|----------|-------------|-------------|--------------|----------------|-------|-------------|');
  heroSlides.forEach((s, idx) => {
    const img = (s.image as Record<string,unknown>);
    const url = str(img?.url);
    const ok  = isCloudinaryUrl(url);
    if (!ok) checkImg(url, `hero[${idx+1}]`);
    checkLink(str(s.primary_button_link), `hero[${idx+1}] primary`);
    checkLink(str(s.secondary_button_link), `hero[${idx+1}] secondary`);
    lines.push(`| ${idx+1} | ${str(s.title)} | ${str(s.subtitle)} | ${str(s.primary_button_text)} | \`${str(s.primary_button_link)}\` | ${str(s.secondary_button_text)} | \`${str(s.secondary_button_link)}\` | \`${url.slice(-40)}\` | ${ok ? '✅' : '❌'} |`);
  });

  lines.push('');
  lines.push('### partners.json');
  lines.push('');
  lines.push('| # | Name | Logo URL (last 50 chars) | Cloudinary? |');
  lines.push('|---|------|--------------------------|-------------|');
  partnerSlides.forEach((p, idx) => {
    const img = (p.logo as Record<string,unknown>);
    const url = str(img?.url);
    const ok  = isCloudinaryUrl(url);
    if (!ok) checkImg(url, `partner[${idx+1}] ${str(p.name)}`);
    lines.push(`| ${idx+1} | ${str(p.name)} | \`…${url.slice(-50)}\` | ${ok ? '✅' : '❌'} |`);
  });

  lines.push('');
  if (nonCloudinary.length === 0) {
    lines.push('✅ All seed image URLs are hosted on Cloudinary.');
  } else {
    lines.push(`❌ ${nonCloudinary.length} non-Cloudinary URL(s):`);
    nonCloudinary.forEach(u => lines.push(`  - ${u}`));
  }

  lines.push('');
  if (badLinks.length === 0) {
    lines.push('✅ All button links are valid internal paths or external URLs.');
  } else {
    lines.push(`❌ ${badLinks.length} suspect button link(s):`);
    badLinks.forEach(l => lines.push(`  - ${l}`));
  }

  return lines;
}

// ── CHECK 5: Warnings & skipped items ───────────────────────────────────────
function check5Warnings(byType: Map<string, Record<string, unknown>[]>): string[] {
  const lines: string[] = [];
  lines.push('## Check 5 – Warnings & Skipped Items');
  lines.push('');

  const warnings: string[] = [];

  // Accommodations: null type
  const accomDocs = byType.get('accommodation') ?? [];
  for (const doc of accomDocs) {
    if (!doc.type && !doc.accommodationType) {
      warnings.push(`[accommodation] ${doc._id}: type is null/missing`);
    }
  }

  // BlogPosts: null category
  const blogDocs = byType.get('blogPost') ?? [];
  for (const doc of blogDocs) {
    if (!doc.category) warnings.push(`[blogPost] ${doc._id}: category is null/missing`);
  }

  // Tours: currency absent → KES
  const tourDocs = byType.get('tour') ?? [];
  for (const doc of tourDocs) {
    const c = str(doc.currency).toUpperCase();
    if (!c) warnings.push(`[tour] ${doc._id} "${str(doc.title)}": currency absent → defaulting to KES`);
    else if (!['KES','USD','EUR'].includes(c)) warnings.push(`[tour] ${doc._id} "${str(doc.title)}": non-standard currency=${c}`);
    if (!doc.location) warnings.push(`[tour] ${doc._id} "${str(doc.title)}": location absent → will store "Unknown"`);
  }

  // Hot deals / popups: archived by design
  const hotDocs   = byType.get('hotDeal') ?? [];
  const popupDocs = byType.get('popupOffer') ?? [];
  if (hotDocs.length)   warnings.push(`[info] ${hotDocs.length} hot_deals imported as status='archived' (by design)`);
  if (popupDocs.length) warnings.push(`[info] ${popupDocs.length} popup_offers imported as status='archived' (by design)`);

  // Gallery images: check and show category counts
  const ALLOWED_GALLERY = new Set(['wildlife','scenery','tours','accommodations','adventures']);
  const galleryCounts   = new Map<string, number>();
  const galleryDocs = byType.get('galleryImage') ?? [];
  for (const doc of galleryDocs) {
    const cat = str(doc.category).toLowerCase();
    galleryCounts.set(cat, (galleryCounts.get(cat) ?? 0) + 1);
    if (cat && !ALLOWED_GALLERY.has(cat)) {
      warnings.push(`[galleryImage] ${doc._id}: category="${cat}" UNKNOWN – migration will throw`);
    } else if (!cat) {
      warnings.push(`[galleryImage] ${doc._id}: category absent → defaults to 'wildlife'`);
    }
  }

  lines.push('### Gallery category counts');
  lines.push('');
  lines.push('| Category (Sanity) | Count | Allowed? |');
  lines.push('|-------------------|-------|----------|');
  for (const [cat, count] of [...galleryCounts.entries()].sort()) {
    const allowed = ALLOWED_GALLERY.has(cat);
    lines.push(`| \`${cat}\` | ${count} | ${allowed ? '✅' : '❌'} |`);
  }
  lines.push('');

  // Fleet vehicles: trimmed names
  const fleetDocs = byType.get('fleetVehicle') ?? [];
  for (const doc of fleetDocs) {
    const raw     = str(doc.name ?? doc.title);
    const trimmed = raw.replace(/\s+/g, ' ').trim();
    if (raw !== trimmed) warnings.push(`[fleetVehicle] ${doc._id}: name trimmed "${raw}" → "${trimmed}"`);
  }

  // Packages: 0 records
  const pkgDocs = byType.get('package') ?? [];
  if (pkgDocs.length === 0) warnings.push('[info] packages: 0 Sanity records – table will be empty');

  warnings.push('[info] hero_slides: 0 Sanity records – seeded from next-app fallbackSlides (6 rows)');
  warnings.push('[info] partners: 0 Sanity records – seeded from next-app fallbackPartners (7 rows)');
  warnings.push('[info] Olare Mara Kempinski draft NOT imported – only published record migrated');

  // themedPackages: duplicate category & rich-text note
  const themedDocs = byType.get('themedPackage') ?? [];
  const themedCats = new Map<string, string[]>();
  for (const td of themedDocs) {
    const c = str(td.category).toLowerCase();
    const list = themedCats.get(c) ?? [];
    list.push(`${td._id} "${str(td.title)}"`);
    themedCats.set(c, list);
  }
  for (const [c, list] of themedCats.entries()) {
    if (list.length > 1) {
      warnings.push(`[themedPackage] UNIQUE constraint conflict on category="${c}": ${list.length} records share this category (${list.join(' | ')}). Migration keeps Adventure Package (2954b894) and skips duplicate 07422e07.`);
    }
  }

  lines.push(`${warnings.length} item(s):`);
  lines.push('');
  warnings.forEach(w => lines.push(`- ${w}`));

  return lines;
}

// ── CHECK 6: Redirect integrity ──────────────────────────────────────────────
function check6Redirects(byType: Map<string, Record<string, unknown>[]>): string[] {
  const lines: string[] = [];
  lines.push('## Check 6 – Redirect Integrity (no chains, no loops) + Type Counts');
  lines.push('');

  const allDocs = [
    ...(byType.get('tour') ?? []),
    ...(byType.get('blogPost') ?? []),
    ...(byType.get('accommodation') ?? []),
    ...(byType.get('destinationPost') ?? []),
  ];

  interface RedirectRow { from: string; to: string; type: string }
  const rows: RedirectRow[] = [];

  function addRow(from: string, to: string, type: string) {
    if (from === to) return;
    rows.push({ from, to, type });
  }

  function isUUID(s: string) {
    return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(s);
  }

  // Build planned slug map (same logic as transformers)
  const accomDocs = byType.get('accommodation') ?? [];
  const accomSlugMap = new Map<string, string>(
    accomDocs.map(d => [d._id as string, slugify(str(d.name ?? d.title))])
  );

  for (const doc of allDocs) {
    const id      = doc._id as string;
    const type    = doc._type as string;
    const rawSlug = str((doc.slug as Record<string,unknown>)?.current);

    let canonical = '';
    if (type === 'tour') {
      canonical = str(doc.title).toUpperCase().includes('VISIT LAMU') ? 'visit-lamu' : slugify(rawSlug || str(doc.title));
    } else if (type === 'blogPost') {
      canonical = str(doc.title).toLowerCase().includes('altitude training') ? 'altitude-training-kenya' : slugify(rawSlug || str(doc.title));
    } else if (type === 'accommodation') {
      canonical = accomSlugMap.get(id) ?? slugify(str(doc.name ?? doc.title));
    } else if (type === 'destinationPost') {
      canonical = rawSlug === 'ambosseli-national-park' ? 'amboseli-national-park' : slugify(rawSlug || str(doc.title));
    }

    if (!canonical) continue;

    // UUID paths
    if (isUUID(id)) {
      if (type === 'tour')           addRow(`/tours/${id}`,             `/tours/${canonical}`,        'tour-uuid');
      if (type === 'blogPost')       addRow(`/blog/${id}`,              `/blog/${canonical}`,          'blog-uuid');
      if (type === 'accommodation')  addRow(`/accommodation/view/${id}`,`/accommodation/${canonical}`, 'accom-uuid');
      if (type === 'destinationPost')addRow(`/destinations/${id}`,      `/destinations/${canonical}`,  'dest-uuid');
    }

    // Dirty slugs
    if (type === 'tour' && rawSlug && rawSlug !== canonical) {
      addRow(`/tours/${rawSlug}`, `/tours/${canonical}`, 'tour-dirty-slug');
      const pct = encodeURIComponent(rawSlug);
      if (pct !== rawSlug) addRow(`/tours/${pct}`, `/tours/${canonical}`, 'tour-pct-encoded');
    }
    if (type === 'blogPost' && rawSlug && rawSlug !== canonical) {
      addRow(`/blog/${rawSlug}`, `/blog/${canonical}`, 'blog-dirty-slug');
      const pct = encodeURIComponent(rawSlug);
      if (pct !== rawSlug) addRow(`/blog/${pct}`, `/blog/${canonical}`, 'blog-pct-encoded');
    }
    if (type === 'destinationPost' && rawSlug === 'ambosseli-national-park') {
      addRow(`/destinations/ambosseli-national-park`, `/destinations/amboseli-national-park`, 'dest-typo');
    }
    // No themed-package redirects (/packages/[category] routes by category slug)
  }

  // Deduplicate
  const seen = new Set<string>();
  const deduped = rows.filter(r => { if (seen.has(r.from)) return false; seen.add(r.from); return true; });

  const toMap  = new Map<string, string>(deduped.map(r => [r.from, r.to]));
  const fromSet = new Set(deduped.map(r => r.from));

  const chains: string[] = [];
  for (const r of deduped) {
    if (fromSet.has(r.to)) chains.push(`CHAIN: ${r.from} → ${r.to} → ${toMap.get(r.to)}`);
  }

  const loops: string[] = [];
  for (const r of deduped) {
    if (toMap.get(r.to) === r.from) loops.push(`LOOP: ${r.from} ↔ ${r.to}`);
  }

  // Count by type
  const typeCounts = new Map<string, number>();
  for (const r of deduped) typeCounts.set(r.type, (typeCounts.get(r.type) ?? 0) + 1);

  // Verify no redirect target returns 404 against planned slugs
  // Build all planned paths
  const plannedPaths = new Set<string>();
  (byType.get('tour') ?? []).forEach(d => {
    const title = str(d.title);
    const rawS  = str((d.slug as Record<string,unknown>)?.current);
    const s = title.toUpperCase().includes('VISIT LAMU') ? 'visit-lamu' : slugify(rawS || title);
    plannedPaths.add(`/tours/${s}`);
  });
  (byType.get('blogPost') ?? []).forEach(d => {
    const title = str(d.title);
    const rawS  = str((d.slug as Record<string,unknown>)?.current);
    const s = title.toLowerCase().includes('altitude training') ? 'altitude-training-kenya' : slugify(rawS || title);
    plannedPaths.add(`/blog/${s}`);
  });
  (byType.get('accommodation') ?? []).forEach(d => {
    plannedPaths.add(`/accommodation/${slugify(str(d.name ?? d.title))}`);
  });
  (byType.get('destinationPost') ?? []).forEach(d => {
    const rawS = str((d.slug as Record<string,unknown>)?.current);
    const s = rawS === 'ambosseli-national-park' ? 'amboseli-national-park' : slugify(rawS || str(d.title));
    plannedPaths.add(`/destinations/${s}`);
  });

  const toPathsWith404: string[] = [];
  for (const r of deduped) {
    if (!plannedPaths.has(r.to)) toPathsWith404.push(`${r.from} → ${r.to} (NOT in planned rows)`);
  }

  lines.push(`Total redirects: **${deduped.length}**`);
  lines.push('');
  lines.push('### Counts by type');
  lines.push('');
  lines.push('| Type | Count | Description |');
  lines.push('|------|-------|-------------|');
  const typeDescriptions: Record<string, string> = {
    'tour-uuid':       'Tour UUID → canonical slug',
    'blog-uuid':       'Blog UUID → canonical slug',
    'accom-uuid':      'Accommodation UUID → canonical slug',
    'dest-uuid':       'Destination UUID → canonical slug',
    'tour-dirty-slug': 'Tour old/raw slug → canonical',
    'tour-pct-encoded':'Tour percent-encoded slug → canonical',
    'blog-dirty-slug': 'Blog old slug → canonical',
    'blog-pct-encoded':'Blog percent-encoded slug → canonical',
    'dest-typo':       'ambosseli → amboseli typo fix',
  };
  for (const [type, count] of [...typeCounts.entries()].sort((a,b) => b[1]-a[1])) {
    lines.push(`| \`${type}\` | ${count} | ${typeDescriptions[type] ?? type} |`);
  }

  lines.push('');
  lines.push(chains.length === 0 ? '✅ No redirect chains.' : `❌ ${chains.length} chain(s):\n${chains.map(c=>'  - '+c).join('\n')}`);
  lines.push('');
  lines.push(loops.length === 0 ? '✅ No redirect loops.' : `❌ ${loops.length} loop(s):\n${loops.map(l=>'  - '+l).join('\n')}`);
  lines.push('');
  if (toPathsWith404.length === 0) {
    lines.push('✅ All redirect targets exist in planned rows (no 404s).');
  } else {
    lines.push(`❌ ${toPathsWith404.length} redirect target(s) not found in planned rows:`);
    toPathsWith404.forEach(r => lines.push(`  - ${r}`));
  }

  lines.push('');
  lines.push('### Full redirect table');
  lines.push('');
  lines.push('| From | To | Type |');
  lines.push('|------|----|------|');
  for (const r of deduped) lines.push(`| \`${r.from}\` | \`${r.to}\` | ${r.type} |`);

  return lines;
}

