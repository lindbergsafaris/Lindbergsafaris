/**
 * report.ts
 *
 * Generates the dry-run report and writes planned rows as JSON to cms-migration/out/.
 */

import { writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = resolve(__dirname, '..', 'out');

export function ensureOutDir() {
  mkdirSync(OUT_DIR, { recursive: true });
}

export function writeJson(name: string, data: unknown) {
  const path = resolve(OUT_DIR, `${name}.json`);
  writeFileSync(path, JSON.stringify(data, null, 2), 'utf8');
  return path;
}

export interface ReportSection {
  table: string;
  count: number;
  skipped?: number;
  warnings?: string[];
}

export interface OlareDiff {
  field: string;
  published: unknown;
  draft: unknown;
}

export function writeReport(opts: {
  sections: ReportSection[];
  olareDiff: OlareDiff[];
  redirectCount: number;
  nonCloudinaryUrls: string[];
  dryRun: boolean;
}) {
  ensureOutDir();

  const lines: string[] = [];
  const ts = new Date().toISOString();
  const mode = opts.dryRun ? '**DRY RUN** – no rows were written' : '**LIVE RUN** – rows committed to Supabase';

  lines.push(`# CMS Migration Report`);
  lines.push(`Generated: ${ts}`);
  lines.push(`Mode: ${mode}`);
  lines.push('');
  lines.push('## Row Counts');
  lines.push('');
  lines.push('| Table | Planned rows | Skipped |');
  lines.push('|-------|-------------|---------|');
  for (const s of opts.sections) {
    lines.push(`| ${s.table} | ${s.count} | ${s.skipped ?? 0} |`);
  }
  lines.push(`| redirects | ${opts.redirectCount} | 0 |`);
  lines.push('');

  const sectionWarnings = opts.sections.flatMap((s) =>
    (s.warnings ?? []).map((w) => `- **[${s.table}]** ${w}`)
  );
  if (sectionWarnings.length > 0) {
    lines.push('## ⚠️ Warnings & Skipped Records');
    lines.push('');
    lines.push(...sectionWarnings);
    lines.push('');
  }

  if (opts.olareDiff.length > 0) {
    lines.push('## Olare Mara Kempinski: Draft vs Published Diff');
    lines.push('');
    lines.push('| Field | Published | Draft |');
    lines.push('|-------|-----------|-------|');
    for (const d of opts.olareDiff) {
      const pub = JSON.stringify(d.published ?? null).slice(0, 120);
      const draft = JSON.stringify(d.draft ?? null).slice(0, 120);
      lines.push(`| ${d.field} | ${pub} | ${draft} |`);
    }
    lines.push('');
    lines.push('> Only the published record is imported. The draft is **not** migrated.');
    lines.push('');
  } else {
    lines.push('## Olare Mara Kempinski');
    lines.push('No differences found between published and draft (or draft not present).');
    lines.push('');
  }

  if (opts.nonCloudinaryUrls.length > 0) {
    lines.push('## ⚠️ Non-Cloudinary Image URLs');
    lines.push('');
    for (const u of opts.nonCloudinaryUrls) {
      lines.push(`- \`${u}\``);
    }
    lines.push('');
  } else {
    lines.push('## Image URLs');
    lines.push('All image URLs are hosted on Cloudinary. ✓');
    lines.push('');
  }

  lines.push('---');
  lines.push('*Report generated by cms-migration. Review before running with --commit.*');

  const content = lines.join('\n');
  const path = resolve(OUT_DIR, 'report.md');
  writeFileSync(path, content, 'utf8');
  return path;
}
